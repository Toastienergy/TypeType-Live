#!/bin/sh
set -eu
cd "$(dirname "$0")"
export PATH="$PATH:$(go env GOPATH)/bin"
test -z "$(gofumpt -l .)" || { gofumpt -l .; echo "gofumpt: files need formatting"; exit 1; }
go vet ./...
golangci-lint run ./...
go test -race -count=1 ./...
govulncheck ./...
deadcode -test ./...
echo "all checks passed"
